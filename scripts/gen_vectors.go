// Vectors for `below` and `scalar`, drawn by Go itself from fixed byte streams:
// crypto/rand.Int for `below`, crypto/ecdsa.GenerateKey for `scalar`. Each
// vector holds exactly the bytes Go read and the values it returned, so a
// replay of those bytes through moonrand must return the same values and use
// every byte.
//
//	go run scripts/gen_vectors.go > src/vectors_test.mbt
package main

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"encoding/binary"
	"fmt"
	"math/big"
	"os"
	"strings"
)

// stream is an endless SHA-256 counter stream, so every vector is reproducible.
type stream struct {
	seed    string
	counter uint64
	buf     []byte
	used    []byte
}

func (s *stream) Read(p []byte) (int, error) {
	for len(s.buf) < len(p) {
		var c [8]byte
		binary.BigEndian.PutUint64(c[:], s.counter)
		s.counter++
		h := sha256.Sum256(append([]byte(s.seed), c[:]...))
		s.buf = append(s.buf, h[:]...)
	}
	copy(p, s.buf)
	s.used = append(s.used, p...)
	s.buf = s.buf[len(p):]
	return len(p), nil
}

// draws hands the reads of one byte, which are randutil.MaybeReadByte, to a
// separate supply and every other read to the stream, so the stream records
// only what randomPoint sampled.
type draws struct {
	prefix []byte
	main   *stream
}

func (d *draws) Read(p []byte) (int, error) {
	if len(p) == 1 {
		p[0] = 0
		return 1, nil
	}
	if len(d.prefix) > 0 {
		n := copy(p, d.prefix)
		d.prefix = d.prefix[n:]
		d.main.used = append(d.main.used, p[:n]...)
		if n == len(p) {
			return n, nil
		}
		m, err := d.main.Read(p[n:])
		return n + m, err
	}
	return d.main.Read(p)
}

func lit(b []byte) string {
	var sb strings.Builder
	sb.WriteString(`b"`)
	for _, x := range b {
		fmt.Fprintf(&sb, `\x%02x`, x)
	}
	sb.WriteString(`"`)
	return sb.String()
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func main() {
	out := os.Stdout
	fmt.Fprintln(out, "// Generated by scripts/gen_vectors.go from Go's crypto/rand and crypto/ecdsa. Edit the script, not this file.")
	fmt.Fprintln(out)

	var bounds []*big.Int
	for _, n := range []int64{1, 2, 3, 7, 8, 9, 127, 128, 129, 139, 255, 256, 257, 1000, 65535, 65536, 65537} {
		bounds = append(bounds, big.NewInt(n))
	}
	for _, s := range []string{
		"ffffffffffffffff",
		"010000000000000001",
		"c9f2c9cd04674edea40000000",
	} {
		n, _ := new(big.Int).SetString(s, 16)
		bounds = append(bounds, n)
	}
	bounds = append(bounds, elliptic.P256().Params().N, elliptic.P521().Params().N)

	fmt.Fprintln(out, "///|")
	fmt.Fprintln(out, "/// A bound, the bytes Go's `crypto/rand.Int` read, and the eight values it returned.")
	fmt.Fprintln(out, "let below_vectors : Array[(Bytes, Bytes, Array[Bytes])] = [")
	for _, bound := range bounds {
		s := &stream{seed: "moonrand below " + bound.Text(16)}
		var values []string
		for range 8 {
			v, err := rand.Int(s, bound)
			must(err)
			values = append(values, lit(v.FillBytes(make([]byte, len(bound.Bytes())))))
		}
		fmt.Fprintf(out, "  (%s, %s, [%s]),\n", lit(bound.Bytes()), lit(s.used), strings.Join(values, ", "))
	}
	fmt.Fprintln(out, "]")
	fmt.Fprintln(out)

	curves := []elliptic.Curve{elliptic.P224(), elliptic.P256(), elliptic.P384(), elliptic.P521()}
	fmt.Fprintln(out, "///|")
	fmt.Fprintln(out, "/// A group order, the bytes Go's `ecdsa.GenerateKey` sampled, and the private key it")
	fmt.Fprintln(out, "/// made of them. The second of each pair starts with a draw above the order and one")
	fmt.Fprintln(out, "/// of zeros, which Go rejects.")
	fmt.Fprintln(out, "let scalar_vectors : Array[(Bytes, Bytes, Bytes)] = [")
	for _, c := range curves {
		order := c.Params().N
		size := len(order.Bytes())
		for _, crafted := range []bool{false, true} {
			s := &stream{seed: "moonrand scalar " + c.Params().Name}
			r := &draws{main: s}
			if crafted {
				high := make([]byte, size)
				for i := range high {
					high[i] = 0xff
				}
				r.prefix = append(high, make([]byte, size)...)
			}
			key, err := ecdsa.GenerateKey(c, r)
			must(err)
			d := key.D.FillBytes(make([]byte, size))
			fmt.Fprintf(out, "  (%s, %s, %s),\n", lit(order.Bytes()), lit(s.used), lit(d))
		}
	}
	fmt.Fprintln(out, "]")
	fmt.Fprintln(out)
	fmt.Fprint(out, `///|
test "below returns what Go's crypto/rand.Int returns, from the same bytes" {
  for v in below_vectors {
    let (bound, stream, values) = v
    let source = @moonrand.Replay::new(stream)
    for value in values {
      assert_eq(@moonrand.below(bound, source), value)
    }
    assert_eq(source.remaining(), 0)
  }
}

///|
test "scalar returns the key Go's ecdsa.GenerateKey makes, from the same bytes" {
  for v in scalar_vectors {
    let (order, stream, key) = v
    let source = @moonrand.Replay::new(stream)
    assert_eq(@moonrand.scalar(order, source), key)
    assert_eq(source.remaining(), 0)
  }
}
`)
}
